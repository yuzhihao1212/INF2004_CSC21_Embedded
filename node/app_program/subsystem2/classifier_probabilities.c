void classifier_probabilities(const int32_t logits[3],uint16_t p[3]) {
    int32_t largest=logits[0];
    for (int i=1;i<3;++i) if (logits[i]>largest) largest=logits[i];
    uint32_t weight[3],sum=0;
    for (int i=0;i<3;++i) {
        int64_t delta=(int64_t)largest-logits[i];
        /* Logit distance -> table index, rounded to nearest:
         * index = delta * 1579172 / 2^24, about one step per 10.6 logit units. */
        int64_t index=(delta*1579172+((int64_t)1<<23))>>24;
        weight[i]=index>512 ? 0 : exp_q15[index];
        sum+=weight[i];
    }
    p[0]=(uint16_t)((weight[0]*32768u)/sum);
    p[1]=(uint16_t)((weight[1]*32768u)/sum);
    p[2]=(uint16_t)(32768u-p[0]-p[1]);
}
